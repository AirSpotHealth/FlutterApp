  dfuUpdateFail,
  co2Retry,
  flightMode,
  scaling,
  sdkError,
  faultReset,
  empty,
  rawCo2,
  sampleCorrection,
  sampleTemperature,
  sampleHumidity,
  samplePressure,
  sampleBatteryPercent,
  sampleBatteryMv,
  sampleAscMode,
  sampleStatus,
  sampleFlags,
  sampleQi,
  measurementModeChange;

  static DeviceDataType fromByte(int byte) =>
      deviceDataByteMap[byte] ?? DeviceDataType.empty;

  @override
  String toString() => humanizedName;

  String get humanizedName => deviceDataTypeMap[this] ?? '-';
}

